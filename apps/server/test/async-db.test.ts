import { afterEach, beforeEach, describe, expect, test } from "vitest";
import { openPglite } from "../src/server/db-pglite.ts";
import type { Db } from "../src/server/db.ts";

describe("Db and PGlite transactions", () => {
  let db: Db & { close(): Promise<void> };

  beforeEach(async () => {
    db = await openPglite();

    await db.exec(`
      CREATE TABLE items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL
      );
    `);
  });

  afterEach(async () => {
    await db.close();
  });

  test("db.get, db.all, db.run work (run returns { changes })", async () => {
    const runResult = await db.run("INSERT INTO items (name) VALUES (?)", "first");
    expect(runResult).toEqual({ changes: 1 });

    const getResult = await db.get<{ id: number; name: string }>(
      "SELECT id, name FROM items WHERE name = ?",
      "first"
    );
    expect(getResult).toBeDefined();
    expect(getResult?.id).toBe(1);
    expect(getResult?.name).toBe("first");

    await db.run("INSERT INTO items (name) VALUES (?)", "second");

    const allResult = await db.all<{ id: number; name: string }>(
      "SELECT id, name FROM items ORDER BY id ASC"
    );
    expect(allResult).toHaveLength(2);
    expect(allResult[0].name).toBe("first");
    expect(allResult[1].name).toBe("second");
  });

  test("INSERT … RETURNING id through db.get returns the id", async () => {
    const row = await db.get<{ id: number }>(
      "INSERT INTO items (name) VALUES (?) RETURNING id",
      "returned-item"
    );
    expect(row).toBeDefined();
    expect(typeof row?.id).toBe("number");
    expect(row?.id).toBe(1);
  });

  test("db.tx commits; db.tx whose body throws rolls back and rethrows", async () => {
    await db.tx(async () => {
      await db.run("INSERT INTO items (name) VALUES (?)", "committed");
    });

    const rowsAfterCommit = await db.all<{ name: string }>("SELECT name FROM items");
    expect(rowsAfterCommit.map((r) => r.name)).toEqual(["committed"]);

    await expect(
      db.tx(async () => {
        await db.run("INSERT INTO items (name) VALUES (?)", "rolled-back");
        throw new Error("intentional error");
      })
    ).rejects.toThrow("intentional error");

    const rowsAfterRollback = await db.all<{ name: string }>("SELECT name FROM items");
    expect(rowsAfterRollback.map((r) => r.name)).toEqual(["committed"]);
  });

  test("a nested db.tx joins the outer one (the outer throw rolls back the inner write too)", async () => {
    await expect(
      db.tx(async () => {
        await db.run("INSERT INTO items (name) VALUES (?)", "outer-item");
        await db.tx(async () => {
          await db.run("INSERT INTO items (name) VALUES (?)", "inner-item");
        });
        throw new Error("outer error");
      })
    ).rejects.toThrow("outer error");

    const rows = await db.all<{ name: string }>("SELECT name FROM items");
    expect(rows).toHaveLength(0);
  });

  test("two concurrent db.tx calls whose bodies await new Promise(r => setTimeout(r, 20)) never overlap", async () => {
    const events: string[] = [];

    const p1 = db.tx(async () => {
      events.push("enter1");
      await new Promise((r) => setTimeout(r, 20));
      events.push("exit1");
    });

    const p2 = db.tx(async () => {
      events.push("enter2");
      await new Promise((r) => setTimeout(r, 20));
      events.push("exit2");
    });

    await Promise.all([p1, p2]);
    expect(events).toEqual(["enter1", "exit1", "enter2", "exit2"]);
  });

  test("the write mutex releases after a rejected fn: a later db.tx still runs", async () => {
    await expect(
      db.tx(async () => {
        throw new Error("rejected transaction");
      })
    ).rejects.toThrow("rejected transaction");

    const result = await db.tx(async () => {
      await db.run("INSERT INTO items (name) VALUES (?)", "subsequent-item");
      return "success";
    });

    expect(result).toBe("success");
    const rows = await db.all<{ name: string }>("SELECT name FROM items");
    expect(rows.map((r) => r.name)).toEqual(["subsequent-item"]);
  });
});
